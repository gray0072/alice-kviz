// Сколько последних званий каждого уровня не повторять.
const RECENT_TITLES = 10;

function tierOf(score, total) {
  return TIERS.findIndex((t) => score >= t.min * total);
}

/**
 * Выбирает звание за результат, которого не было среди последних RECENT_TITLES этого уровня.
 * @param {number[][]} memory application_state.tt — индексы последних званий по уровням
 * @returns {{ text: string, memory: number[][] }} фраза со званием и обновлённая память
 */
function pickTitle(score, total, memory, rng = Math.random) {
  const tier = tierOf(score, total);
  const { names, before, after } = TIERS[tier];
  const mem = TIERS.map((_, i) => (Array.isArray(memory) && Array.isArray(memory[i]) ? memory[i] : []));
  const limit = Math.min(RECENT_TITLES, names.length - 1);
  const used = new Set(mem[tier].slice(-limit));
  const free = names.map((_, i) => i).filter((i) => !used.has(i));
  const idx = free[Math.floor(rng() * free.length)];
  mem[tier] = mem[tier].slice(-limit).concat(idx).slice(-limit);
  const text = `${before}Звание — ${names[idx]}!${after ? ` ${after}` : ''}`;
  return { text, memory: mem };
}

module.exports = { TIERS, RECENT_TITLES, tierOf, pickTitle };
