// Сколько последних реакций каждого типа не повторять. Меньше размера списка, чтобы было из чего выбрать.
const RECENT = { right: 15, trick: 10, silly: 10, skipped: 2 };

/**
 * Выбирает реакцию, которой не было среди последних RECENT[kind].
 * @param {string} kind right | trick | silly | skipped
 * @param {object} memory { [kind]: number[] } — индексы последних реакций (из session_state)
 * @returns {{ text: string, memory: object }} реакция и обновлённая память (исходная не меняется)
 */
function pickReaction(kind, memory = {}, rng = Math.random) {
  const list = REACTIONS[kind];
  const limit = Math.min(RECENT[kind], list.length - 1);
  const recent = (Array.isArray(memory[kind]) ? memory[kind] : []).slice(-limit);
  const used = new Set(recent);
  const free = list.map((_, i) => i).filter((i) => !used.has(i));
  const idx = free[Math.floor(rng() * free.length)];
  return { text: list[idx], memory: { ...memory, [kind]: recent.concat(idx).slice(-limit) } };
}

module.exports = { REACTIONS, RECENT, pickReaction };
