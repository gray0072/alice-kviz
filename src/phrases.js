const COUNT_WORDS = { 5: 'пять', 6: 'шесть', 7: 'семь', 8: 'восемь', 9: 'девять', 10: 'десять' };

const countWord = (n) => COUNT_WORDS[n] || String(n);
const otherLevel = (lv) => (lv === 1 ? 'сложный' : 'лёгкий');
const otherCount = (n) => (n === 10 ? 'пять' : 'десять');

// «уровень сложный и десять вопросов» — только то, что изменилось (или всё, если ничего).
function settingsText(lv, n) {
  const parts = [];
  if (lv) parts.push(`${LEVEL_NAMES[lv]} уровень`);
  if (n) parts.push(`${countWord(n)} вопросов`);
  return parts.join(' и ');
}

